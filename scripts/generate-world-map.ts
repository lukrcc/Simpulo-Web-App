/** world-atlas → the land as one SVG path in Natural Earth (no borders, no Antarctica). Run by hand; the result is checked in. */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { geoBounds, geoNaturalEarth1, geoPath } from "d3-geo";
import type { Feature, MultiPolygon } from "geojson";
import { feature } from "topojson-client";
import type { GeometryCollection, Topology } from "topojson-specification";
import land from "world-atlas/land-110m.json";

const WIDTH = 1000;
const HEIGHT = 480;

const topology = land as unknown as Topology<{ land: GeometryCollection }>;
const world = feature(topology, topology.objects.land);
const polygons = world.features.flatMap((f) => (f.geometry.type === "MultiPolygon" ? f.geometry.coordinates : f.geometry.type === "Polygon" ? [f.geometry.coordinates] : []));
const shape: Feature<MultiPolygon> = {
  type: "Feature",
  properties: {},
  geometry: {
    type: "MultiPolygon",
    coordinates: polygons.filter((coordinates) => geoBounds({ type: "Polygon", coordinates })[1][1] > -60),
  },
};

const projection = geoNaturalEarth1().fitSize([WIDTH, HEIGHT], shape);
const d = geoPath(projection).digits(1)(shape) ?? "";

const out = `// Generated by scripts/generate-world-map.ts. Do not edit.
export const WORLD_WIDTH = ${WIDTH};
export const WORLD_HEIGHT = ${HEIGHT};
export const WORLD_SCALE = ${projection.scale()};
export const WORLD_TRANSLATE: [number, number] = [${projection.translate().join(", ")}];
export const WORLD_LAND = ${JSON.stringify(d)};
`;
writeFileSync(path.resolve(__dirname, "../src/lib/data/world-map.generated.ts"), out);
console.log(`world map: ${d.length} characters, scale ${projection.scale()}`);
