import { existsSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

/** Node only: which destinations have a file under public/destinations. Writes the list the app reads, and MISSING.md. */
export function syncDestinationImages(root: string, curatedSlugs: readonly string[]) {
  const folder = path.join(root, "public", "destinations");
  const files = existsSync(folder) ? readdirSync(folder) : [];
  const slugs = files.filter((f) => f.endsWith(".jpg")).map((f) => f.slice(0, -4)).toSorted();
  writeFileSync(
    path.join(root, "src", "lib", "data", "destination-images.generated.ts"),
    `// Generated by scripts/sync-destination-images.ts from public/destinations/*.jpg – don't edit.\nexport const CURATED_IMAGE_SLUGS: readonly string[] = ${JSON.stringify(slugs, null, 2)};\n`,
  );
  const missing = curatedSlugs.filter((slug) => !slugs.includes(slug));
  writeFileSync(
    path.join(folder, "MISSING.md"),
    `# Destinations without an image (${missing.length} of ${curatedSlugs.length})\n\nAdd as public/destinations/<slug>.jpg: landscape, at least 1600px wide, no people or brand logos. Then run scripts/sync-destination-images.ts (it runs before dev and build).\n\n${missing.map((slug) => `- ${slug}`).join("\n")}\n`,
  );
  return { slugs, missing };
}
