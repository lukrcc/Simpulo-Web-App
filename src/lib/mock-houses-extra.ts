export interface ExtraHost {
  id: string;
  name: string;
  age: number;
  country: string;
  city: string;
  languages: string[];
  bio: string;
  verified: boolean;
  /** Professional host: runs hosted experiences and may charge a host fee */
  isPro: boolean;
  canChargeHostFee: boolean;
  /** One-line job/credential shown on pro profiles, e.g. "Certified kite instructor (IKO)" */
  proTitle?: string;
  socials: Partial<Record<'instagram' | 'tiktok' | 'youtube' | 'linkedin' | 'x' | 'threads' | 'twitch' | 'kick' | 'website', string>>;
  /** Pixabay queries: [0] face/portrait, [1..2] lifestyle */
  imageQueries: [string, string, string];
}

export interface ExtraHouse {
  id: string;
  slug: string;
  title: string;
  hostId: string;
  vibe: ExtraVibe;
  city: string;
  region: string;
  lat: number;
  lng: number;
  startDate: string;
  endDate: string;
  spotsTotal: number;
  spotsFilled: number;
  /** open houses: budget range; locked houses: pricePerPerson */
  budgetPerPerson?: { min: number; max: number };
  pricePerPerson?: number;
  currency: 'EUR';
  accommodationStatus: 'open' | 'locked';
  status: 'published' | 'full' | 'completed';
  acceptingRequests: boolean;
  featured: boolean;
  language: string;
  hostNote: string;
  description: string;
  whyText: string;
  dayText: string;
  lookingForText: string;
  houseRules: string[];
  interests: string[];
  /** Pro hosts only (feature flag hostPremium). Must be ≤ 30 % of the accommodation share. */
  hostFeePerPerson?: number;
  /** What the host fee pays for – shown as a checklist on the house page */
  hostOffer?: string[];
  /** Optional age range the host is aiming for (singles, 40+ etc.) */
  ageRange?: { min: number; max: number };
  /** Pixabay queries: [0] cover, [1..3] gallery */
  imageQueries: [string, string, string, string];
  createdAt: string;
}

